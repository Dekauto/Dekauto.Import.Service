namespace Dekauto.Import.Service.Domain.Entities.Adapters
{
    /// <summary>
    /// Адаптер для передачи файлов Excel в контроллер импорта
    /// </summary>
    /// <remarks>
    /// Используется для передачи набора файлов Excel, необходимых для импорта данных о студентах.
    /// Все файлы должны быть в формате .xlsx.
    /// </remarks>
    public class ImportFilesAdapter
    {
        /// <summary>
        /// Файл личного дела (Личное дело)
        /// </summary>
        /// <remarks>
        /// Excel файл с персональными данными студентов:
        /// - ФИО, дата рождения, место рождения
        /// - Паспортные данные
        /// - Адреса регистрации и проживания
        /// - Данные об образовании (аттестат/диплом)
        /// - Результаты вступительных испытаний
        /// </remarks>
        public IFormFile? ld { get; set; }

        /// <summary>
        /// Файл договоров (Договор об образовании)
        /// </summary>
        /// <remarks>
        /// Excel файл с информацией о договорах на обучение:
        /// - Дата заключения договора
        /// - Номер договора
        /// - Номер и дата приказа о зачислении
        /// </remarks>
        public IFormFile? contract { get; set; }

        /// <summary>
        /// Файл журнала (Журнал зачетных книжек)
        /// </summary>
        /// <remarks>
        /// Excel файл с информацией о зачетных книжках и группах:
        /// - Номер зачетной книжки
        /// - Номер группы
        /// </remarks>
        public IFormFile? journal { get; set; }

        /// <summary>
        /// Файл ведомости (Ведомость успеваемости)
        /// </summary>
        /// <remarks>
        /// Excel файл с оценками по дисциплинам:
        /// - Названия дисциплин (в строках 6-7)
        /// - Оценки студентов
        /// - Информация о семестре и годе обучения (в строках 2-4)
        /// - Типы контроля (экзамен, зачет, курсовая работа, практика)
        /// </remarks>
        public IFormFile? statement { get; set; }

        /// <summary>
        /// Файл учебного плана (Учебный план)
        /// </summary>
        /// <remarks>
        /// Excel файл с учебным планом:
        /// - Лист "ПланСвод" с дисциплинами, аудиторными часами и зачетными единицами
        /// - Листы "Курс 1", "Курс 2", "Курс 3", "Курс 4" с типами контроля по семестрам
        /// - Столбец 5 - название дисциплины
        /// - Столбец 7 - тип контроля для нечетных семестров
        /// - Столбец 22 - тип контроля для четных семестров
        /// </remarks>
        public IFormFile? plan { get; set; }

        /// <summary>
        /// Файл карточки студента (для приложения диплома)
        /// </summary>
        /// <remarks>
        /// Опциональный файл с дополнительной информацией о студенте.
        /// В настоящее время не используется в основном процессе импорта.
        /// </remarks>
        public IFormFile? studentCard { get; set; }

    }
}
